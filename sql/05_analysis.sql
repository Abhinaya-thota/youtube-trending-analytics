-- 05_analysis.sql: the headline findings in SQL, matching findings_check.py and
-- compare_countries.py. Each query reads VIDEO_PEAK (one row per video).

USE SCHEMA YT_DB.YT_SCHEMA;

-- Views and engagement by category (US).
SELECT
  m.CATEGORY_NAME,
  COUNT(*) AS VIDEOS,
  SUM(p.VIEWS) / 1e9 AS TOTAL_VIEWS_BILLIONS,
  AVG(p.ENGAGEMENT_RATE) AS MEAN_ENGAGEMENT
FROM VIDEO_PEAK p
JOIN CATEGORY_MAP m ON m.CATEGORY_ID = p.CATEGORY_ID
WHERE p.COUNTRY = 'US'
GROUP BY m.CATEGORY_NAME
HAVING COUNT(*) >= 200
ORDER BY TOTAL_VIEWS_BILLIONS DESC;

-- Engagement by publish weekday, UTC (1 = Monday ... 7 = Sunday).
SELECT
  DAYOFWEEKISO(PUBLISHED_AT) AS PUBLISH_WEEKDAY,
  COUNT(*) AS VIDEOS,
  AVG(ENGAGEMENT_RATE) AS MEAN_ENGAGEMENT
FROM VIDEO_PEAK
WHERE COUNTRY = 'US'
GROUP BY PUBLISH_WEEKDAY
ORDER BY PUBLISH_WEEKDAY;

-- Engagement by publish weekday and hour, UTC (heatmap source).
SELECT
  DAYOFWEEKISO(PUBLISHED_AT) AS PUBLISH_WEEKDAY,
  PUBLISH_HOUR,
  COUNT(*) AS VIDEOS,
  AVG(ENGAGEMENT_RATE) AS MEAN_ENGAGEMENT
FROM VIDEO_PEAK
WHERE COUNTRY = 'US'
GROUP BY PUBLISH_WEEKDAY, PUBLISH_HOUR
ORDER BY PUBLISH_WEEKDAY, PUBLISH_HOUR;

-- Country comparison.
SELECT
  COUNTRY,
  COUNT(*) AS VIDEOS,
  SUM(VIEWS) / 1e9 AS TOTAL_VIEWS_BILLIONS,
  AVG(ENGAGEMENT_RATE) AS MEAN_ENGAGEMENT,
  AVG(CASE WHEN POPULARITY_TIER = 'Viral' THEN 1 ELSE 0 END) * 100 AS VIRAL_SHARE
FROM VIDEO_PEAK
GROUP BY COUNTRY
ORDER BY COUNTRY;

-- Top 10 most viewed US videos.
SELECT TITLE, CHANNELTITLE, VIEWS, ENGAGEMENT_RATE
FROM VIDEO_PEAK
WHERE COUNTRY = 'US'
ORDER BY VIEWS DESC
LIMIT 10;
